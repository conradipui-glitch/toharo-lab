/**
 * Форматы изображений на сайте.
 *
 * Правило: изображение генерируется СРАЗУ в тех пропорциях, в которых
 * оно ляжет в блок. Иначе браузер обрежет его по object-cover как попало,
 * и с картинки уедет смысловой центр.
 *
 * Один пост = одна обложка формата `cover` (16:9). Она же идёт в карточку,
 * в шапку поста и в OpenGraph — пропорции близкие, кроп незаметен.
 * Остальные форматы нужны, только если появится новый тип блока.
 */

export type ImageFormat = "cover" | "square" | "wide";

export type FormatSpec = {
  /** Ширина в пикселях, в которой генерируем. */
  width: number;
  /** Высота в пикселях. */
  height: number;
  /** Соотношение сторон для CSS. */
  ratio: string;
  /** Где применяется — подсказка для агента. */
  usedFor: string;
};

export const IMAGE_FORMATS: Record<ImageFormat, FormatSpec> = {
  // Основной формат. Карточка обрезает до 16:10, шапка показывает целиком,
  // OpenGraph обрезает до 1.91:1 — все три кропа не трогают центр кадра.
  cover: {
    width: 1600,
    height: 900,
    ratio: "16 / 9",
    usedFor: "обложка поста: карточка в ленте, шапка статьи, превью в соцсетях",
  },
  square: {
    width: 1200,
    height: 1200,
    ratio: "1 / 1",
    usedFor: "компактные списки и плитки (сейчас на сайте не используется)",
  },
  wide: {
    width: 1680,
    height: 720,
    ratio: "21 / 9",
    usedFor: "широкий баннер во всю ширину (сейчас на сайте не используется)",
  },
};

export const DEFAULT_FORMAT: ImageFormat = "cover";

/** Путь к обложке поста по его slug. */
export function coverPath(slug: string): string {
  return `/covers/${slug}.jpg`;
}
